/** Metadata only: this does not select a renderer or relax any source parser. */
function recipe(
  id: BusinessRecipeId,
  kind: BusinessRecipe['kind'],
  preset: string,
  owner: BusinessPack,
  objective: string,
  sourceRequirements: readonly string[],
  assets: readonly BusinessAssetId[],
  treatments: readonly BusinessTreatmentId[],
  modes: readonly ExplanationVisualMode[] = BOTH,
): BusinessRecipe {
  return {
    id,
    kind,
    preset,
    owner,
    objective,
    sourceRequirements,
    modes,
    assets,
    treatments,
    fixtureIds: [`business-${id}`],
  };
}

