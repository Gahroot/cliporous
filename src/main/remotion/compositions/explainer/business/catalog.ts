export function businessRecipe(kind: string, preset: string): BusinessRecipe | null {
  return BUSINESS_RECIPES.find((entry) => entry.kind === kind && entry.preset === preset) ?? null;
}

export function businessModeAllowed(
  kind: string,
  preset: string,
  mode: ExplanationVisualMode,
): boolean {
  return businessRecipe(kind, preset)?.modes.includes(mode) ?? false;
}
